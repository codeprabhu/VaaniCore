"""Convert a trained Keras model to a fully int8 TFLite C array."""
from __future__ import annotations

import argparse
import json
import pathlib
import sys

import numpy as np

ROOT = pathlib.Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))
from tools.provenance import generated_provenance


def _blocked(path: pathlib.Path, config: dict, status: str, reason: str) -> int:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps({"provenance": generated_provenance(config), "status": status,
                                "label": "NOT_A_RESULT", "reason": reason}, indent=2) + "\n")
    print(path)
    return 2


def main() -> int:
    parser = argparse.ArgumentParser(description="Export an int8 TFLite model and C byte array")
    parser.add_argument("--model", required=True)
    parser.add_argument("--representative", required=True, help=".npy/.npz array shaped N x 124 x 10")
    parser.add_argument("--output", default="firmware/components/model/model_data.cc")
    parser.add_argument("--status", default="results/ml_export_status.json")
    args = parser.parse_args()
    config = {"model": args.model, "representative": args.representative, "output": args.output}
    status = ROOT / args.status
    try:
        import tensorflow as tf
    except ImportError:
        return _blocked(status, config, "BLOCKED_TOOLCHAIN", "TensorFlow is not installed")
    model_path = ROOT / args.model
    rep_path = ROOT / args.representative
    if not model_path.exists() or not rep_path.exists():
        return _blocked(status, config, "BLOCKED_INPUT", "trained model and representative data are required")
    values = np.load(rep_path)
    if isinstance(values, np.lib.npyio.NpzFile):
        values = values[values.files[0]]
    values = np.asarray(values, dtype=np.float32)
    if values.ndim == 3:
        values = values[..., None]
    if values.ndim != 4 or tuple(values.shape[1:]) != (124, 10, 1):
        raise SystemExit("representative data must have shape N x 124 x 10 or N x 124 x 10 x 1")
    converter = tf.lite.TFLiteConverter.from_saved_model(str(model_path))
    converter.optimizations = [tf.lite.Optimize.DEFAULT]
    converter.representative_dataset = lambda: ([sample] for sample in values)
    converter.target_spec.supported_ops = [tf.lite.OpsSet.TFLITE_BUILTINS_INT8]
    converter.inference_input_type = tf.int8
    converter.inference_output_type = tf.int8
    blob = converter.convert()
    output = ROOT / args.output
    output.parent.mkdir(parents=True, exist_ok=True)
    array = ", ".join(f"0x{byte:02x}" for byte in blob)
    output.write_text("// Generated by ml/export_tflite.py; verify and understand before firmware use.\n"
                      "#include <cstdint>\n\n"
                      f"alignas(16) const unsigned char g_vaanicore_model[] = {{{array}}};\n"
                      f"const unsigned int g_vaanicore_model_len = {len(blob)};\n")
    status.parent.mkdir(parents=True, exist_ok=True)
    status.write_text(json.dumps({"provenance": generated_provenance(config), "status": "EXPORTED",
                                  "label": "MODEL_ARTIFACT — NOT AN ACCURACY RESULT", "bytes": len(blob),
                                  "output": str(output)}, indent=2) + "\n")
    print(output)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

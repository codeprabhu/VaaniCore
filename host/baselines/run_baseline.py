"""P2/P3 baseline entry point; refuses to emit scores without real inputs."""
from __future__ import annotations
import argparse, json, pathlib, sys
try:
    from tools.provenance import generated_provenance
except ModuleNotFoundError:
    sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[2]))
    from tools.provenance import generated_provenance

def main() -> None:
    parser = argparse.ArgumentParser(description="Run P2 hybrid or P3 host-only ASR baseline")
    parser.add_argument("--partition", choices=("P2", "P3"), required=True)
    parser.add_argument("--audio", help="recorded WAV or stream capture")
    parser.add_argument("--model", help="local Vosk/faster-whisper model directory")
    parser.add_argument("--output", default="results/baseline_status.json")
    args = parser.parse_args()
    missing = [name for name, value in (("audio", args.audio), ("model", args.model)) if not value or not pathlib.Path(value).exists()]
    data = {"provenance": generated_provenance(vars(args)), "partition": args.partition, "label": "NOT_A_RESULT", "status": "BLOCKED_HUMAN" if missing else "READY_FOR_IMPLEMENTATION", "missing": missing, "note": "No ASR score is generated by this scaffold."}
    output = pathlib.Path(args.output); output.parent.mkdir(parents=True, exist_ok=True); output.write_text(json.dumps(data, indent=2) + "\n"); print(output)
if __name__ == "__main__": main()
